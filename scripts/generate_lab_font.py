LAYOUT_KEYS = (
    "text_x", "text_max_width", "list_width", "indicator_right", "indicator_gap",
    "title_baseline", "rows_top", "row_height", "row_baseline", "rows",
    "footer_baseline", "max_wide_chars",
)  # fmt: skip
UI_KEYS = ("menu_title", "menu_footer", "detail_footer", "detail_footer_launch", "indicator")
TOPIC_KEYS = ("id", "menu", "title", "launch", "pages")


class Page(NamedTuple):
    indicator: str
    lines: Tuple[str, ...]


class Topic(NamedTuple):
    id: str
    label: str
    indicator: str
    title: str
    footer: str
    launch: Optional[str]
    pages: Tuple[Page, ...]


class Content(NamedTuple):
    layout: Dict[str, int]
    menu_title: str
    menu_footer: str
    topics: Tuple[Topic, ...]

    def strings(self) -> Iterable[str]:
        yield self.menu_title
        yield self.menu_footer
        for topic in self.topics:
            yield from (topic.label, topic.indicator, topic.title, topic.footer)
            for page in topic.pages:
                yield page.indicator
                yield from page.lines


def _object(value, where: str, keys: Tuple[str, ...], optional: Tuple[str, ...] = ()) -> dict:
    if not isinstance(value, dict):
        raise ContentError(f"{where} must be an object")
    unknown = sorted(set(value) - set(keys) - set(optional))
    missing = [key for key in keys if key not in value]
    if unknown or missing:
        raise ContentError(f"{where}: unknown keys {unknown}, missing keys {missing}")
    return value


def _text(value, where: str, max_wide: int) -> str:
    if not isinstance(value, str) or not value:
        raise ContentError(f"{where} must be a non-empty string")
    if value != value.strip():
        raise ContentError(f"{where} has leading or trailing whitespace")
    for char in value:
        code = ord(char)
        if code < 0x20 or 0x7F <= code < 0xA0 or 0xD800 <= code < 0xE000 or code > 0xFFFD:
            raise ContentError(f"{where} contains unsupported {describe(code)}")
    wide = sum(1 for char in value if ord(char) > 0x7F)
    if wide > max_wide:
        raise ContentError(f"{where}: {wide} non-ASCII characters, limit is {max_wide}")
    return value


def _indicator(template: str, index: int, count: int) -> str:
    try:
        return template.format(index=index, count=count)
    except (KeyError, IndexError, ValueError) as error:
        raise ContentError(f"ui.indicator is not a valid template: {error}") from None


def load_content(raw) -> Content:
    """Validate the JSON structure and expand indicators and footers."""
    raw = _object(raw, "content", ("schema_version", "layout", "ui", "topics"), ("notes",))
    if raw["schema_version"] != 1 or isinstance(raw["schema_version"], bool):
        raise ContentError("schema_version must be 1")
    if not isinstance(raw.get("notes", ""), str):
        raise ContentError("notes must be a string")
    layout = _object(raw["layout"], "layout", LAYOUT_KEYS)
    for key, value in layout.items():
        if not isinstance(value, int) or isinstance(value, bool) or not 0 < value <= SCREEN_W:
            raise ContentError(f"layout.{key} must be an integer in 1..{SCREEN_W}")
    wide = layout["max_wide_chars"]
    ui = _object(raw["ui"], "ui", UI_KEYS)
    text = {key: _text(ui[key], f"ui.{key}", wide) for key in UI_KEYS}

    topics_raw = raw["topics"]
    if not isinstance(topics_raw, list) or not 1 <= len(topics_raw) <= 99:
        raise ContentError("topics must be a list of 1..99 topics")
    topics, ids = [], set()
    for number, item in enumerate(topics_raw, 1):
        where = f"topics[{number - 1}]"
        item = _object(item, where, TOPIC_KEYS)
        topic_id = item["id"]
        if not isinstance(topic_id, str) or not re.fullmatch(r"[a-z][a-z0-9_]*", topic_id):
            raise ContentError(f"{where}.id must be a lowercase C identifier")
        if topic_id in ids:
            raise ContentError(f"duplicate topic id {topic_id!r}")
        ids.add(topic_id)
        launch = item["launch"]
        if launch is not None and not (isinstance(launch, str) and launch.strip()):
            raise ContentError(f"{where}.launch must be null or an app name")
        pages_raw = item["pages"]
        if not isinstance(pages_raw, list) or not 1 <= len(pages_raw) <= 99:
            raise ContentError(f"{where}.pages must be a list of 1..99 pages")
        pages = []
        for page_number, lines in enumerate(pages_raw, 1):
            page_where = f"{where}.pages[{page_number - 1}]"
            if not isinstance(lines, list) or not 1 <= len(lines) <= layout["rows"]:
                raise ContentError(f"{page_where} must hold 1..{layout['rows']} lines")
            lines = [_text(line, f"{page_where}[{i}]", wide) for i, line in enumerate(lines)]
            lines += [""] * (layout["rows"] - len(lines))
            indicator = _indicator(text["indicator"], page_number, len(pages_raw))
            pages.append(Page(_text(indicator, f"{page_where} indicator", wide), tuple(lines)))
        footer = text["detail_footer_launch" if launch else "detail_footer"]
        indicator = _indicator(text["indicator"], number, len(topics_raw))
        topics.append(
            Topic(
                topic_id,
                _text(item["menu"], f"{where}.menu", wide),
                _text(indicator, f"{where} indicator", wide),
                _text(item["title"], f"{where}.title", wide),
                footer,
                launch,
                tuple(pages),
            )
        )
    return Content(dict(layout), text["menu_title"], text["menu_footer"], tuple(topics))


def known_launch_names(apps_root: Path) -> Set[str]:
    """Names the loader resolves: MENUEXTERNAL apps and SETTINGS apps."""
    names = set()
    for group in ("main", "settings"):
        for manifest in sorted((apps_root / group).glob("*/application.fam")):
            tree = ast.parse(manifest.read_text(encoding="utf-8"), str(manifest))
            for node in ast.walk(tree):
                if not (isinstance(node, ast.Call) and getattr(node.func, "id", "") == "App"):
                    continue
                args = {kw.arg: kw.value for kw in node.keywords}
                apptype, name = args.get("apptype"), args.get("name")
                if (
                    isinstance(apptype, ast.Attribute)
                    and apptype.attr in LAUNCH_APP_TYPES
                    and isinstance(name, ast.Constant)
                    and isinstance(name.value, str)
                ):
                    names.add(name.value)
    return names


def check_launch_targets(content: Content, names: Set[str]):
    for topic in content.topics:
        if topic.launch is not None and topic.launch not in names:
            raise ContentError(
                f"topic {topic.id!r} launches {topic.launch!r}, which is not the name of "
                "a MENUEXTERNAL or SETTINGS app in applications/main or applications/settings"
            )


def screen_bands(layout: Dict[str, int]) -> Dict[str, Tuple[int, int, int]]:
    """Vertical bands as (top row, bottom row, baseline); rules sit between."""
    rule_top = layout["rows_top"] - 1
    rule_bottom = layout["rows_top"] + layout["rows"] * layout["row_height"]
    if rule_top < 1 or rule_bottom > SCREEN_H - 2:
        raise ContentError("layout rows do not leave room for the title and footer")
    if layout["row_baseline"] > layout["row_height"]:
        raise ContentError("layout.row_baseline must lie inside a row")
    return {
        "title": (0, rule_top - 1, layout["title_baseline"]),
        "row": (0, layout["row_height"] - 1, layout["row_baseline"]),  # per-row offsets
        "footer": (rule_bottom + 1, SCREEN_H - 1, layout["footer_baseline"]),
    }


def check_layout(content: Content, metrics: Metrics):
    """Every string must stay inside its horizontal limit and vertical band."""
    layout = content.layout
    bands = screen_bands(layout)
    x, max_width = layout["text_x"], layout["text_max_width"]
    if not x + max_width <= layout["list_width"] <= SCREEN_W - 4:
        raise ContentError("text must fit the list box, which must leave a scrollbar")
    if layout["indicator_right"] > SCREEN_W:
        raise ContentError("layout.indicator_right is off screen")

    def fit(text: str, band: str, limit: int, where: str):
        if not text:
            return
        width = metrics.width(text)
        left, right, above, below = metrics.ink(text)
        top, bottom, baseline = bands[band]
        if width > limit or right > limit or x + left < 0:
            raise ContentError(f"{where} {text!r} is {max(width, right)} px, limit {limit}")
        if baseline - above < top or baseline + below - 1 > bottom:
            raise ContentError(f"{where} {text!r} leaves its {band} band vertically")

    def fit_title(title: str, indicators: List[str], where: str):
        widest = max(metrics.width(indicator) for indicator in indicators)
        limit = layout["indicator_right"] - widest - layout["indicator_gap"] - x
        fit(title, "title", limit, where)
        for indicator in indicators:
            fit(indicator, "title", layout["indicator_right"], f"{where} indicator")

    fit_title(content.menu_title, [t.indicator for t in content.topics], "menu title")
    fit(content.menu_footer, "footer", max_width, "menu footer")
    for topic in content.topics:
        where = f"topic {topic.id!r}"
        fit(topic.label, "row", max_width, f"{where} menu label")
        fit(topic.footer, "footer", max_width, f"{where} footer")
        fit_title(topic.title, [page.indicator for page in topic.pages], f"{where} title")
        for number, page in enumerate(topic.pages, 1):
            for line in page.lines:
                fit(line, "row", max_width, f"{where} page {number}")


def required_codes(content: Content) -> Set[int]:
    return set(PRINTABLE_ASCII) | {ord(char) for text in content.strings() for char in text}


def verify_subset(source: Font, subset_data: bytes, codes: Set[int]) -> Font:
    """Re-parse the subset and check the device lookup finds the same glyphs."""
    subset = parse_font(subset_data)
    if set(subset.ascii) | set(subset.unicode) != codes:
        raise FontError("subset glyph set differs from the requested characters")
    for code in sorted(codes):
        if u8g2_lookup(subset_data, code) != source.payload(code):
            raise FontError(f"device lookup of {describe(code)} returns wrong data")
        decode_glyph(subset.params, subset.payload(code))
    for code in sorted({c + 1 for c in codes} - codes):
        if u8g2_lookup(subset_data, code) is not None:
            raise FontError(f"device lookup invents a glyph for {describe(code)}")
    return subset


