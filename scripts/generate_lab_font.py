# C source extraction


_SIMPLE_ESCAPES = {
    "n": 10, "t": 9, "r": 13, "a": 7, "b": 8, "f": 12, "v": 11,
    "\\": 92, "'": 39, '"': 34, "?": 63,
}  # fmt: skip
_OCTAL_DIGITS = "01234567"
_HEX_DIGITS = "0123456789abcdefABCDEF"


def decode_c_string(body: str) -> bytes:
    """Decode the text between the quotes of one C string literal."""
    out = bytearray()
    i = 0
    while i < len(body):
        char = body[i]
        if char != "\\":
            if not " " <= char <= "~" or char == '"':
                raise FontError(f"unexpected character {char!r} in string literal")
            out.append(ord(char))
            i += 1
            continue
        i += 1
        if i == len(body):
            raise FontError("string literal ends with a backslash")
        char = body[i]
        if char in _OCTAL_DIGITS:  # at most three octal digits, as in C
            end = i
            while end < len(body) and end - i < 3 and body[end] in _OCTAL_DIGITS:
                end += 1
            value = int(body[i:end], 8)
        elif char == "x":  # C hex escapes consume every following hex digit
            end = i + 1
            while end < len(body) and body[end] in _HEX_DIGITS:
                end += 1
            if end == i + 1:
                raise FontError("\\x escape without hex digits")
            value = int(body[i + 1 : end], 16)
        elif char in _SIMPLE_ESCAPES:
            value, end = _SIMPLE_ESCAPES[char], i + 1
        else:
            raise FontError(f"unsupported escape \\{char}")
        if value > 0xFF:
            raise FontError(f"escape value {value:#x} does not fit in a byte")
        out.append(value)
        i = end
    return bytes(out)


def extract_font(source: str, symbol: str) -> Tuple[bytes, List[str]]:
    """Return the bytes of `symbol` and the upstream comment lines above it."""
    pattern = re.compile(
        r"const\s+uint8_t\s+" + re.escape(symbol) + r"\s*\[\s*(\d+)\s*\]\s*"
        r'(?:U8G2_FONT_SECTION\s*\(\s*"[^"\n]*"\s*\)\s*)?='
    )
    found = list(pattern.finditer(source))
    if len(found) != 1:
        raise FontError(f"expected one definition of {symbol}, found {len(found)}")
    match = found[0]
    declared = int(match.group(1))

    data = bytearray()
    literals = 0
    pos = match.end()
    while True:
        while pos < len(source) and source[pos] in " \t\r\n":
            pos += 1
        if pos == len(source):
            raise FontError(f"{symbol}: initializer is not terminated")
        if source[pos] == ";":
            break
        if source[pos] != '"':
            raise FontError(f"{symbol}: unexpected {source[pos]!r} in initializer")
        end = pos + 1
        while end < len(source) and source[end] != '"':
            if source[end] == "\n":
                break
            end += 2 if source[end] == "\\" else 1
        if end >= len(source) or source[end] != '"':
            raise FontError(f"{symbol}: unterminated string literal")
        data += decode_c_string(source[pos + 1 : end])
        literals += 1
        pos = end + 1
    if not literals:
        raise FontError(f"{symbol}: initializer has no string literal")
    # A char array keeps the literal's terminating NUL only when it has room.
    if declared == len(data) + 1:
        data.append(0)
    elif declared != len(data):
        raise FontError(
            f"{symbol}: literal holds {len(data)} bytes, array is declared [{declared}]"
        )
    return bytes(data), _upstream_comment(source[: match.start()], symbol)


def _upstream_comment(before: str, symbol: str) -> List[str]:
    end = before.rfind("*/")
    start = before.rfind("/*", 0, end)
    if end < 0 or start < 0:
        raise FontError(f"{symbol}: no upstream comment above the definition")
    for line in before[end + 2 :].splitlines():
        if line.strip() and not line.strip().startswith("#"):
            raise FontError(f"{symbol}: upstream comment is not directly above it")
    lines = [line.strip() for line in before[start + 2 : end].splitlines()]
    lines = [line.replace("*/", "* /") for line in lines if line]
    keys = {line.partition(":")[0] for line in lines if ":" in line}
    for key in ("Fontname", "Copyright", "Glyphs"):
        if key not in keys:
            raise FontError(f"{symbol}: upstream comment has no {key} field")
    guards = [line.strip() for line in before[end + 2 :].splitlines() if line.strip()]
    return lines + [f"(definition guarded by: {' '.join(guards)})"] if guards else lines


