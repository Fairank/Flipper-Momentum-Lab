def describe(code: int) -> str:
    char = chr(code)
    return f"U+{code:04X} {char!r}" if char.isprintable() else f"U+{code:04X}"


def be16(data: bytes, offset: int) -> int:
    return (data[offset] << 8) | data[offset + 1]


