def c_string(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("?", "\\?")
    return f'"{escaped}"'


def render_font_header(data: bytes, subset: Font, comment: List[str], source: str,
                       symbol: str, source_data: bytes) -> str:  # fmt: skip
    rows = [
        "    " + ", ".join(f"0x{byte:02x}" for byte in data[i : i + 12]) + ","
        for i in range(0, len(data), 12)
    ]
    upstream = "\n".join(f" *   {line}" for line in comment)
    return f"""/* {GENERATED_NOTE}
 *
 * u8g2 font subset for Flipper Lab: printable ASCII plus every character in
 * lab_content.json. Taken from {symbol} in {source}
 * ({len(source_data)} bytes, sha256 {hashlib.sha256(source_data).hexdigest()}).
 * Upstream comment above that definition, verbatim:
{upstream}
 * Glyph payloads are copied unchanged. Only the header offsets, glyph count and
 * the single-block Unicode lookup table are rebuilt. Origin and licence notes:
 * applications/main/lab/README.md
 *
 * Subset: {len(subset.ascii)} 8-bit + {len(subset.unicode)} Unicode glyphs, {len(data)} bytes.
 */
#pragma once

#include <stdint.h>

#define LAB_FONT_GLYPHS {len(subset.ascii) + len(subset.unicode)}

static const uint8_t lab_font[] = {{
{chr(10).join(rows)}
}};
"""


def render_content_header(content: Content) -> str:
    layout = content.layout
    bands = screen_bands(layout)
    max_bytes = max(len(text.encode("utf-8")) for text in content.strings())
    defines = {
        "LAB_TEXT_X": layout["text_x"],
        "LAB_TEXT_MAX_W": layout["text_max_width"],
        "LAB_LIST_W": layout["list_width"],
        "LAB_INDICATOR_RIGHT": layout["indicator_right"],
        "LAB_INDICATOR_GAP": layout["indicator_gap"],
        "LAB_TITLE_Y": bands["title"][2],
        "LAB_RULE_TOP": bands["title"][1] + 1,
        "LAB_ROWS_TOP": layout["rows_top"],
        "LAB_ROW_H": layout["row_height"],
        "LAB_ROW_BASELINE": layout["row_baseline"],
        "LAB_ROWS": layout["rows"],
        "LAB_RULE_BOTTOM": bands["footer"][0] - 1,
        "LAB_FOOTER_Y": bands["footer"][2],
        "LAB_TEXT_MAX_BYTES": max_bytes,
        "LAB_TOPIC_COUNT": len(content.topics),
    }
    out = [
        f"/* {GENERATED_NOTE}",
        " * Source: applications/main/lab/lab_content.json",
        " * Every string was measured against lab_font.h for its screen area.",
        " */",
        "#pragma once",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
    ]
    out += [f"#define {name} {value}" for name, value in defines.items()]
    out += [
        "",
        "typedef struct {",
        "    const char* indicator;",
        "    const char* lines[LAB_ROWS];",
        "} LabPage;",
        "",
        "typedef struct {",
        "    const char* label;",
        "    const char* indicator;",
        "    const char* title;",
        "    const char* footer;",
        "    const char* launch; /* loader app name, or NULL */",
        "    const LabPage* pages;",
        "    uint8_t page_count;",
        "} LabTopic;",
        "",
        f"static const char lab_menu_title[] = {c_string(content.menu_title)};",
        f"static const char lab_menu_footer[] = {c_string(content.menu_footer)};",
    ]
    for topic in content.topics:
        out += ["", f"static const LabPage lab_pages_{topic.id}[] = {{"]
        for page in topic.pages:
            lines = ", ".join(c_string(line) for line in page.lines)
            out.append(f"    {{{c_string(page.indicator)}, {{{lines}}}}},")
        out.append("};")
    out += ["", "static const LabTopic lab_topics[LAB_TOPIC_COUNT] = {"]
    for topic in content.topics:
        launch = c_string(topic.launch) if topic.launch else "NULL"
        out += [
            "    {",
            f"        .label = {c_string(topic.label)},",
            f"        .indicator = {c_string(topic.indicator)},",
            f"        .title = {c_string(topic.title)},",
            f"        .footer = {c_string(topic.footer)},",
            f"        .launch = {launch},",
            f"        .pages = lab_pages_{topic.id},",
            f"        .page_count = {len(topic.pages)},",
            "    },",
        ]
    out += ["};", ""]
    return "\n".join(out)


def generate(source: Path, symbol: str, content_path: Path,
             launch_names: Optional[Set[str]] = None) -> Tuple[str, str]:  # fmt: skip
    """Return the text of (lab_font.h, lab_content.h)."""
    try:
        source_text = source.read_text(encoding="latin-1")
        raw = json.loads(content_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, ValueError) as error:
        raise GeneratorError(f"cannot read inputs: {error}") from None
    content = load_content(raw)
    if launch_names is not None:
        check_launch_targets(content, launch_names)
    source_data, comment = extract_font(source_text, symbol)
    font = parse_font(source_data)
    codes = required_codes(content)
    data = build_subset(font, codes)
    subset = verify_subset(font, data, codes)
    check_layout(content, Metrics(subset))
    source_name = _shown(source) if source.resolve().is_relative_to(ROOT) else source.name
    return (
        render_font_header(data, subset, comment, source_name, symbol, source_data),
        render_content_header(content),
    )


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if outputs are stale")
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--symbol", default=DEFAULT_SYMBOL)
    parser.add_argument("--content", type=Path, default=DEFAULT_CONTENT)
    parser.add_argument("--font-out", type=Path, default=DEFAULT_FONT_OUT)
    parser.add_argument("--content-out", type=Path, default=DEFAULT_CONTENT_OUT)
    parser.add_argument(
        "--apps-root",
        type=Path,
        default=DEFAULT_APPS_ROOT,
        help="applications/ directory used to validate launch names",
    )
    parser.add_argument("--no-app-check", action="store_true", help="skip launch-name check")
    args = parser.parse_args(argv)

    try:
        names = None if args.no_app_check else known_launch_names(args.apps_root)
        font_h, content_h = generate(args.source, args.symbol, args.content, names)
    except (GeneratorError, OSError, SyntaxError, ValueError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2

    stale = []
    for path, text in ((args.font_out, font_h), (args.content_out, content_h)):
        data = text.encode("utf-8")
        if path.exists() and path.read_bytes() == data:
            continue
        if args.check:
            stale.append(path)
        else:
            path.write_bytes(data)
            print(f"wrote {_shown(path)}")
    for path in stale:
        print(f"stale: {_shown(path)} (run scripts/generate_lab_font.py)", file=sys.stderr)
    return 1 if stale else 0


def _shown(path: Path) -> str:
    try:
        return path.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return str(path)


if __name__ == "__main__":
    sys.exit(main())
