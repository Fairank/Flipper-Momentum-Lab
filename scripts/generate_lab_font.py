# u8g2 font format


class GlyphParams(NamedTuple):
    bits_0: int
    bits_1: int
    width: int
    height: int
    x: int
    y: int
    advance: int


class Glyph(NamedTuple):
    width: int
    height: int
    x: int
    y: int
    advance: int
    pixels: FrozenSet[Tuple[int, int]]  # (column, row), row 0 at the glyph top
    bits: int  # payload bits read by the decoder


class Font(NamedTuple):
    header: bytes
    ascii: Dict[int, bytes]  # encoding <= 0xFF -> glyph payload
    unicode: Dict[int, bytes]  # encoding > 0xFF -> glyph payload

    @property
    def params(self) -> GlyphParams:
        return GlyphParams(*self.header[2:9])

    def payload(self, code: int) -> Optional[bytes]:
        return (self.ascii if code <= 0xFF else self.unicode).get(code)


class _Bits:
    """LSB-first bit reader matching u8g2_font_decode_get_unsigned_bits()."""

    def __init__(self, payload: bytes):
        self.payload = payload
        self.pos = 0

    def unsigned(self, count: int) -> int:
        if self.pos + count > len(self.payload) * 8:
            raise FontError("glyph bitstream runs past its record")
        value = 0
        for i in range(count):
            bit = self.pos + i
            value |= ((self.payload[bit >> 3] >> (bit & 7)) & 1) << i
        self.pos += count
        return value

    def signed(self, count: int) -> int:
        return self.unsigned(count) - (1 << (count - 1))


def decode_glyph(params: GlyphParams, payload: bytes) -> Glyph:
    """Decode one glyph exactly like u8g2_font_decode_glyph()."""
    bits = _Bits(payload)
    width, height = bits.unsigned(params.width), bits.unsigned(params.height)
    x, y, advance = (bits.signed(n) for n in (params.x, params.y, params.advance))
    pixels = set()
    if width > 0:
        col = row = 0

        def run(length: int, ink: bool):
            nonlocal col, row
            while True:  # u8g2_font_decode_len()
                remaining = width - col
                if ink:
                    pixels.update((col + i, row) for i in range(min(length, remaining)))
                if length < remaining:
                    break
                length -= remaining
                col, row = 0, row + 1
            col += length

        while True:
            zeros, ones = bits.unsigned(params.bits_0), bits.unsigned(params.bits_1)
            while True:
                run(zeros, False)
                run(ones, True)
                if not bits.unsigned(1):
                    break
            if row >= height:
                break
        if any(py >= height for _, py in pixels):
            raise FontError("glyph draws below its bounding box")
    spare = len(payload) - (bits.pos + 7) // 8
    if spare > 1:
        raise FontError(f"glyph record has {spare} unused trailing bytes")
    return Glyph(width, height, x, y, advance, frozenset(pixels), bits.pos)


def parse_font(data: bytes) -> Font:
    """Parse and validate a u8g2 font, following lib/u8g2/u8g2_font.c."""
    if len(data) < HEADER_SIZE + 8:
        raise FontError("font is shorter than its header and tables")
    header = data[:HEADER_SIZE]
    params = GlyphParams(*header[2:9])
    if not all(1 <= n <= 8 for n in params):
        raise FontError(f"unsupported glyph bit widths {tuple(params)}")
    # w, h, x, y and advance fields precede the run-length data of every glyph
    min_payload = (sum(params[2:]) + 7) // 8

    ascii_glyphs: Dict[int, bytes] = {}
    starts: List[Tuple[int, int]] = []  # (offset from byte 23, encoding)
    pos = HEADER_SIZE
    while True:
        if pos + 2 > len(data):
            raise FontError("8-bit glyph table is truncated")
        code, size = data[pos], data[pos + 1]
        if size == 0:
            break
        if size < 2 + min_payload or pos + size > len(data):
            raise FontError(f"8-bit glyph {describe(code)} has a bad length {size}")
        if starts and code <= starts[-1][1]:
            raise FontError(f"8-bit glyph {describe(code)} is duplicated or unsorted")
        starts.append((pos - HEADER_SIZE, code))
        ascii_glyphs[code] = data[pos + 2 : pos + size]
        pos += size
    terminator = pos - HEADER_SIZE
    for field, first in ((17, "A"), (19, "a")):
        start = be16(header, field)
        if start != terminator and start not in {offset for offset, _ in starts}:
            raise FontError(f"start of '{first}' glyphs is not a record boundary")
        if any(code >= ord(first) for offset, code in starts if offset < start):
            raise FontError(f"start of '{first}' glyphs skips glyphs it must find")
    table = HEADER_SIZE + be16(header, 21)
    if table != pos + 2:
        raise FontError("Unicode section does not follow the 8-bit glyphs")

    blocks: List[Tuple[int, int]] = []  # (glyph position, last encoding)
    entry = block = table
    while not blocks or blocks[-1][1] != 0xFFFF:
        if entry + 4 > len(data):
            raise FontError("Unicode lookup table is truncated")
        block += be16(data, entry)
        last = be16(data, entry + 2)
        if blocks and last <= blocks[-1][1]:
            raise FontError("Unicode lookup table is not sorted")
        blocks.append((block, last))
        entry += 4
    if blocks[0][0] != entry:
        raise FontError("first Unicode block does not follow the lookup table")

    unicode_glyphs: Dict[int, bytes] = {}
    records: Set[int] = set()
    pos, previous, index = entry, 0xFF, 0
    while True:
        if pos + 2 > len(data):
            raise FontError("Unicode glyph list has no zero sentinel")
        code = be16(data, pos)
        if code == 0:
            break
        size = data[pos + 2] if pos + 2 < len(data) else 0
        if size < 3 + min_payload or pos + size > len(data):
            raise FontError(f"Unicode glyph {describe(code)} has a bad length {size}")
        if code <= previous:
            raise FontError(f"Unicode glyph {describe(code)} is duplicated or unsorted")
        while index + 1 < len(blocks) and blocks[index + 1][0] <= pos:
            index += 1
        if code > blocks[index][1]:
            raise FontError(f"lookup table cannot reach {describe(code)}")
        records.add(pos)
        unicode_glyphs[code] = data[pos + 3 : pos + size]
        previous = code
        pos += size
    if any(start not in records and start != pos for start, _ in blocks):
        raise FontError("a Unicode lookup block does not start at a glyph record")
    if pos + 2 != len(data):
        raise FontError(f"{len(data) - pos - 2} unexpected bytes after the sentinel")
    return Font(bytes(header), ascii_glyphs, unicode_glyphs)


def u8g2_lookup(data: bytes, code: int) -> Optional[bytes]:
    """Return the payload u8g2_font_get_glyph_data() finds for `code`."""
    pos = HEADER_SIZE
    if code <= 0xFF:
        if code >= ord("a"):
            pos += be16(data, 19)
        elif code >= ord("A"):
            pos += be16(data, 17)
        while data[pos + 1] != 0:
            if data[pos] == code:
                return data[pos + 2 : pos + data[pos + 1]]
            pos += data[pos + 1]
        return None
    table = pos = pos + be16(data, 21)
    while True:  # issue 596 block search, then a linear scan
        pos += be16(data, table)
        last = be16(data, table + 2)
        table += 4
        if last >= code:
            break
    while be16(data, pos) != 0:
        if be16(data, pos) == code:
            return data[pos + 3 : pos + data[pos + 2]]
        pos += data[pos + 2]
    return None


def build_subset(font: Font, codes: Iterable[int]) -> bytes:
    """Return a u8g2 font holding exactly `codes`, payloads unchanged."""
    codes = sorted(set(codes))
    missing = [code for code in codes if font.payload(code) is None]
    if missing:
        listed = ", ".join(describe(code) for code in missing)
        raise FontError(f"source font has no glyph for {listed}")

    ascii_part = bytearray()
    upper = lower = None
    for code in (c for c in codes if c <= 0xFF):
        payload = font.ascii[code]
        if code >= ord("A") and upper is None:
            upper = len(ascii_part)
        if code >= ord("a") and lower is None:
            lower = len(ascii_part)
        ascii_part += bytes((code, 2 + len(payload))) + payload
    terminator = len(ascii_part)
    ascii_part += b"\0\0"

    unicode_part = bytearray(struct.pack(">HH", 4, 0xFFFF))  # one block
    for code in (c for c in codes if c > 0xFF):
        payload = font.unicode[code]
        unicode_part += struct.pack(">HB", code, 3 + len(payload)) + payload
    unicode_part += b"\0\0"

    header = bytearray(font.header)
    header[0] = len(codes) & 0xFF  # u8g2 stores the glyph count modulo 256
    offsets = (terminator if upper is None else upper,
               terminator if lower is None else lower,
               len(ascii_part))  # fmt: skip
    for value in offsets:
        if value > 0xFFFF:
            raise FontError(f"8-bit section offset {value} overflows 16 bits")
    header[17:23] = struct.pack(">HHH", *offsets)
    return bytes(header + ascii_part + unicode_part)


class Metrics:
    """Measure text like canvas_string_width() with a given font."""

    def __init__(self, font: Font):
        self.font = font
        self._glyphs: Dict[int, Glyph] = {}

    def glyph(self, code: int) -> Glyph:
        if code not in self._glyphs:
            payload = self.font.payload(code)
            if payload is None:
                raise FontError(f"font has no glyph for {describe(code)}")
            self._glyphs[code] = decode_glyph(self.font.params, payload)
        return self._glyphs[code]

    def width(self, text: str) -> int:
        """u8g2_GetUTF8Width(): advances, with the last glyph's real extent."""
        total = advance = last_width = last_x = 0
        for char in text:
            glyph = self.glyph(ord(char))
            advance, last_width, last_x = glyph.advance, glyph.width, glyph.x
            total += advance
        if last_width:
            total += last_width + last_x - advance
        return total

    def ink(self, text: str) -> Tuple[int, int, int, int]:
        """(left, right, above, below): pixels drawn around the pen origin."""
        pen, left, right, above, below = 0, 0, 0, 0, 0
        for char in text:
            glyph = self.glyph(ord(char))
            if glyph.width and glyph.height:
                left = min(left, pen + glyph.x)
                right = max(right, pen + glyph.x + glyph.width)
                above = max(above, glyph.height + glyph.y)
                below = max(below, -glyph.y)
            pen += glyph.advance
        return left, right, above, below


